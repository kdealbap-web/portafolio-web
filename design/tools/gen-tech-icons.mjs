/**
 * Extracts the brand marks this site actually names into a small registry.
 *
 * `simple-icons` is a devDependency and never reaches the browser: this script
 * pulls the handful of paths we use into a generated TypeScript file, so the
 * bundle carries those marks and nothing else. Re-run it after adding a
 * technology to site.data.ts:
 *
 *   node design/tools/gen-tech-icons.mjs
 *
 * Marks the package does not carry — Oracle and SQL Server were withdrawn at
 * the trademark holders' request — are deliberately absent. The component
 * falls back to a typographic chip for those rather than to a drawing of a
 * logo nobody licensed us to redraw.
 */
import * as si from 'simple-icons';
import { writeFileSync } from 'node:fs';

/** slug in simple-icons → how this site refers to the technology. */
const WANTED = [
  'angular',
  'typescript',
  'reactivex', // RxJS is the JavaScript ReactiveX implementation
  'springboot',
  'openjdk',
  'postgresql',
  'mysql',
  'nodedotjs',
  'deno',
  'php',
  'react',
  'vite',
  'vitest',
  'sass',
  'cloudflare',
  'vercel',
  'supabase',
  'leaflet',
  'tailwindcss',
  'vmware',
  'docker',
  'gitlab',
  'git',
  'prestashop',
  'talend',
  'hibernate',
  'mongodb',
  'veeam',
  'materialdesign',
  'sonarqubeserver',
];

const key = (slug) => 'si' + slug.charAt(0).toUpperCase() + slug.slice(1);

/**
 * A version of the brand colour that survives the petrol ground.
 *
 * Several marks are black or near-black by brand — Vercel, Deno, OpenJDK,
 * Angular — and painting those on a #070e11 page renders them invisible. So we
 * measure relative luminance and, below the threshold, lift the colour toward
 * the page's own text instead of showing a hole where the logo should be.
 * Above it the real brand colour is used untouched.
 */
const TEXT = [0xe8, 0xf0, 0xf1]; // --text, what we lift toward
const FLOOR = 0.17; // relative luminance a mark needs on #070e11

function luminance([r, g, b]) {
  const channel = (v) => {
    const c = v / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

function tintFor(hex) {
  const rgb = [
    parseInt(hex.slice(0, 2), 16),
    parseInt(hex.slice(2, 4), 16),
    parseInt(hex.slice(4, 6), 16),
  ];
  if (luminance(rgb) >= FLOOR) return hex;

  // Walk toward the page's text colour in twentieths and stop at the first
  // step that clears the floor. A purple stays purple, just brighter; a brand
  // that is genuinely black has no hue to preserve and ends up near the text,
  // which is the honest result.
  for (let step = 1; step <= 20; step++) {
    const mix = rgb.map((c, i) => Math.round(c + (TEXT[i] - c) * (step / 20)));
    if (luminance(mix) >= FLOOR) {
      return mix.map((c) => c.toString(16).padStart(2, '0')).join('');
    }
  }
  return TEXT.map((c) => c.toString(16).padStart(2, '0')).join('');
}

const found = [];
const missing = [];

for (const slug of WANTED) {
  const icon = si[key(slug)];
  if (!icon) {
    missing.push(slug);
    continue;
  }
  found.push({ slug, title: icon.title, hex: icon.hex, tint: tintFor(icon.hex), path: icon.path });
}

const body = found
  .map(
    (i) =>
      `  ${i.slug}: {\n` +
      `    title: ${JSON.stringify(i.title)},\n` +
      `    hex: '#${i.hex}',\n` +
      `    tint: '#${i.tint}',\n` +
      `    path:\n      ${JSON.stringify(i.path)},\n` +
      `  },`,
  )
  .join('\n');

const out = `/* GENERATED by design/tools/gen-tech-icons.mjs — do not edit by hand.
 *
 * Brand marks from simple-icons (CC0-1.0), reduced to the ${found.length} this site
 * names. Each is a single path on a 24 grid, so it drops straight into the
 * same icon plumbing as the hand-drawn set.
 */

export interface TechMark {
  /** The brand's own name, used for the accessible label. */
  title: string;
  /** The brand's own colour, kept for reference. */
  hex: string;
  /** The colour actually painted: the brand's, unless it vanishes on petrol. */
  tint: string;
  path: string;
}

export const TECH_MARKS: Record<string, TechMark> = {
${body}
};
`;

writeFileSync(new URL('../../src/app/ui/tech/tech-marks.generated.ts', import.meta.url), out, 'utf8');

console.log(`wrote ${found.length} marks`);
if (missing.length) console.log(`not in simple-icons: ${missing.join(', ')}`);
